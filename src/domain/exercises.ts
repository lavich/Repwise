export function findStep(exerciseId: ExerciseId, stepId: string): LoadStep | undefined {
  return EXERCISES[exerciseId].loadSteps.find((step) => step.id === stepId)
}

export function stepIndex(exerciseId: ExerciseId, stepId: string): number {
  return EXERCISES[exerciseId].loadSteps.findIndex((step) => step.id === stepId)
}

export function stepLabel(exerciseId: ExerciseId, stepId: string): string {
  return findStep(exerciseId, stepId)?.label ?? stepId
}
